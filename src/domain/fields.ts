export function fieldsFor(stage: Stage): FieldDefinition[] {
  return FIELDS.filter((field) => field.stage === stage);
}

export function fieldByKey(stage: Stage, key: string): FieldDefinition | undefined {
  return FIELDS.find((field) => field.stage === stage && field.key === key);
}

export function sectionsFor(stage: Stage): SectionDefinition[] {
  return SECTIONS.filter((section) => section.stage === stage);
}
